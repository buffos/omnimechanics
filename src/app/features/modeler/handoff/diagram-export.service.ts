import { Injectable } from '@angular/core';
import { ProjectDocument } from './handoff.types';

export type SvgInput = SVGSVGElement | { innerHtml: string; width?: number; height?: number };

@Injectable({
  providedIn: 'root',
})
export class DiagramExportService {
  /**
   * Generates a self-contained, publication-grade SVG string from an SVG element or mock data.
   */
  generateStandaloneSvg(
    svgInput: SvgInput,
    title: string = 'OmniMechanics Mode 2 Diagram',
    diagramType: 'M' | 'Q' | 'N' = 'M',
    lang: 'el' | 'en' = 'el'
  ): string {
    const diagLabel =
      diagramType === 'M'
        ? lang === 'el'
          ? 'Διάγραμμα Καμπτικών Ροπών M(x) [kNm] (Ίνα Εφελκυσμού κάτω)'
          : 'Bending Moment Diagram M(x) [kNm] (Bottom Tension Fiber)'
        : diagramType === 'Q'
        ? lang === 'el'
          ? 'Διάγραμμα Τεμνουσών Δυνάμεων Q(x) [kN]'
          : 'Shear Force Diagram Q(x) [kN]'
        : lang === 'el'
        ? 'Διάγραμμα Αξονικών Δυνάμεων N(x) [kN] (+: Εφελκυσμός)'
        : 'Axial Force Diagram N(x) [kN] (+: Tension)';

    if (
      typeof document === 'undefined' ||
      !(typeof (globalThis as any).Element !== 'undefined' && svgInput instanceof (globalThis as any).Element)
    ) {
      const wNum = ('width' in svgInput && typeof svgInput.width === 'number' ? svgInput.width : undefined) ?? 1200;
      const hNum = ('height' in svgInput && typeof svgInput.height === 'number' ? svgInput.height : undefined) ?? 700;
      const content = 'innerHtml' in svgInput ? svgInput.innerHtml : '';
      return `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${wNum}" height="${hNum}" viewBox="0 0 ${wNum} ${hNum}">
  <style>
    text { font-family: Inter, system-ui, -apple-system, sans-serif; }
    .title-block text { fill: #1e293b; }
    .legend text { fill: #475569; font-size: 11px; }
  </style>
  ${content}
  <g class="publication-overlay">
    <g class="title-block" transform="translate(20, 30)">
      <text font-size="16" font-weight="bold" fill="#0f172a">${title}</text>
      <text font-size="12" fill="#64748b" y="18">${diagLabel}</text>
    </g>
    <g class="legend" transform="translate(${wNum - 240}, 30)">
      <rect width="220" height="50" rx="6" fill="#ffffff" fill-opacity="0.9" stroke="#cbd5e1" stroke-width="1"/>
      <circle cx="15" cy="20" r="5" fill="#3b82f6"/>
      <text x="28" y="24">${lang === 'el' ? 'Μέλη & Διαγράμματα' : 'Members & Diagrams'}</text>
    </g>
  </g>
</svg>`;
    }

    const svgElement = svgInput as SVGSVGElement;
    const clone = svgElement.cloneNode(true) as SVGSVGElement;

    // Ensure width, height, and viewBox are present
    const rect = svgElement.getBoundingClientRect();
    const width = rect.width > 0 ? rect.width : 1200;
    const height = rect.height > 0 ? rect.height : 700;

    clone.setAttribute('version', '1.1');
    clone.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
    clone.setAttribute('xmlns:xlink', 'http://www.w3.org/1999/xlink');
    clone.setAttribute('width', `${width}`);
    clone.setAttribute('height', `${height}`);

    // Inline stylesheet
    const styleEl = document.createElementNS('http://www.w3.org/2000/svg', 'style');
    styleEl.textContent = `
      text { font-family: Inter, system-ui, -apple-system, sans-serif; }
      .title-block text { fill: #1e293b; }
      .legend text { fill: #475569; font-size: 11px; }
      .scale-bar text { fill: #64748b; font-size: 10px; }
    `;
    clone.insertBefore(styleEl, clone.firstChild);

    // Title Block and Legend Overlay
    const overlay = document.createElementNS('http://www.w3.org/2000/svg', 'g');
    overlay.setAttribute('class', 'publication-overlay');

    overlay.innerHTML = `
      <g class="title-block" transform="translate(20, 30)">
        <text font-size="16" font-weight="bold" fill="#0f172a">${title}</text>
        <text font-size="12" fill="#64748b" y="18">${diagLabel}</text>
        <text font-size="10" fill="#94a3b8" y="32">Generated by OmniMechanics Mode 2 • ${new Date().toLocaleDateString()}</text>
      </g>
      <g class="legend" transform="translate(${width - 240}, 30)">
        <rect width="220" height="50" rx="6" fill="#ffffff" fill-opacity="0.9" stroke="#cbd5e1" stroke-width="1"/>
        <circle cx="15" cy="20" r="5" fill="#3b82f6"/>
        <text x="28" y="24">${lang === 'el' ? 'Μέλη & Διαγράμματα' : 'Members & Diagrams'}</text>
        <circle cx="15" cy="38" r="5" fill="#ef4444"/>
        <text x="28" y="42">${lang === 'el' ? 'Ακραίες Τιμές / Extrema' : 'Critical Extrema'}</text>
      </g>
    `;
    clone.appendChild(overlay);

    const serializer = new XMLSerializer();
    return `<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n${serializer.serializeToString(clone)}`;
  }

  /**
   * Triggers download of standalone SVG file.
   */
  downloadSvg(
    svgElement: SVGSVGElement,
    filename: string = 'structural-diagram.svg',
    diagramType: 'M' | 'Q' | 'N' = 'M',
    lang: 'el' | 'en' = 'el'
  ): void {
    const svgStr = this.generateStandaloneSvg(svgElement, filename.replace('.svg', ''), diagramType, lang);
    const blob = new Blob([svgStr], { type: 'image/svg+xml;charset=utf-8' });
    this.triggerDownloadBlob(blob, filename);
  }

  /**
   * Renders SVG to an offscreen HTML5 canvas at high DPI and downloads PNG.
   */
  async downloadPng(
    svgElement: SVGSVGElement,
    filename: string = 'structural-diagram.png',
    scale: number = 2.0,
    diagramType: 'M' | 'Q' | 'N' = 'M',
    lang: 'el' | 'en' = 'el'
  ): Promise<void> {
    const svgStr = this.generateStandaloneSvg(svgElement, filename.replace('.png', ''), diagramType, lang);
    const rect = svgElement.getBoundingClientRect();
    const width = (rect.width > 0 ? rect.width : 1200) * scale;
    const height = (rect.height > 0 ? rect.height : 700) * scale;

    const canvas = document.createElement('canvas');
    canvas.width = width;
    canvas.height = height;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    // Fill white background for paper publication
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, width, height);

    const img = new Image();
    const svgBlob = new Blob([svgStr], { type: 'image/svg+xml;charset=utf-8' });
    const url = URL.createObjectURL(svgBlob);

    return new Promise((resolve, reject) => {
      img.onload = () => {
        ctx.drawImage(img, 0, 0, width, height);
        URL.revokeObjectURL(url);
        canvas.toBlob((blob) => {
          if (blob) {
            this.triggerDownloadBlob(blob, filename);
            resolve();
          } else {
            reject(new Error('Canvas blob conversion failed'));
          }
        }, 'image/png');
      };
      img.onerror = (e) => {
        URL.revokeObjectURL(url);
        reject(e);
      };
      img.src = url;
    });
  }

  /**
   * Exports project document as downloadable JSON file (.bem).
   */
  exportProjectFile(doc: ProjectDocument, filename: string = 'project.bem'): string {
    const jsonStr = JSON.stringify(doc, null, 2);
    const blob = new Blob([jsonStr], { type: 'application/json;charset=utf-8' });
    this.triggerDownloadBlob(blob, filename);
    return jsonStr;
  }

  /**
   * Parses and validates a project JSON string.
   */
  importProjectFile(jsonContent: string): ProjectDocument {
    const doc = JSON.parse(jsonContent) as ProjectDocument;
    if (!doc.version || !doc.structural || !Array.isArray(doc.structural.nodes)) {
      throw new Error('Invalid .bem project file format: missing structural nodes.');
    }
    return doc;
  }

  private triggerDownloadBlob(blob: Blob, filename: string): void {
    if (typeof window === 'undefined') return;
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }
}
